// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
export function getAuthorById(id: string): Author | undefined {
  return mockAuthors.find((a) => a.id === id);
}

export function getBookById(id: string): Book | undefined {
  return mockBooks.find((b) => b.id === id);
}

export function getRelatedBooks(book: Book, limit = 3): Book[] {
  return mockBooks
    .filter(
      (b) =>
        b.id !== book.id &&
        b.categories.some((c) => book.categories.includes(c)),
    )
    .slice(0, limit);
}
